#!/usr/bin/env node
/* Regenerate checksums.json from the latest GitHub release of each product.
   GitHub publishes a sha256 digest per asset; the site is static, so the file
   is generated by the Checksums workflow (schedule + repository_dispatch) and
   can also be run by hand with `npm run checksums:gen`.

   2026-11-21 起改从 monorepo（Rocktier/Rocktier-softwares）取数：八款软件的
   Release 都发布在同一个仓里，标签形如 `<slug>/vX.Y.Z`，按前缀取各应用最新版。
   monorepo 上某应用还没有 release 时沿用旧条目（迁移过渡期），绝不写空条目 ——
   空条目会把站点的 checksums 兜底链路打断。 */

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { MONO_REPO, PRODUCTS } from "./products.mjs";

const HERE = dirname(fileURLToPath(import.meta.url));
const OUT = join(HERE, "..", "checksums.json");

const WIN_PREFS = [/x64-setup\.exe$/i, /x64.*\.msi$/i, /\.msi$/i];

function pick(assets, patterns) {
  for (const re of patterns) {
    const hit = assets.find((a) => re.test(a.name));
    if (hit) return hit;
  }
  return null;
}

function entry(asset) {
  if (!asset) return {};
  const [algo, hash] = String(asset.digest || "").split(":");
  if (algo !== "sha256" || !hash) {
    console.warn(`  ! ${asset.name} has no sha256 digest, skipped`);
    return {};
  }
  return { name: asset.name, url: asset.browser_download_url, sha256: hash };
}

let previous = null;
try {
  previous = JSON.parse(readFileSync(OUT, "utf8"));
} catch {}

const headers = { "User-Agent": "rocktier-site-tools", Accept: "application/vnd.github+json" };
const res = await fetch(`https://api.github.com/repos/${MONO_REPO}/releases?per_page=100`, { headers });
if (!res.ok) throw new Error(`${MONO_REPO}: GitHub API ${res.status}`);
const releases = await res.json();
if (!Array.isArray(releases)) throw new Error(`${MONO_REPO}: releases 响应不是列表`);

function latestFor(prefix) {
  let hit = null;
  for (const rel of releases) {
    const tag = String((rel && rel.tag_name) || "");
    if (!tag.startsWith(prefix + "/")) continue;
    if (!hit || String(rel.published_at || "") > String(hit.published_at || "")) hit = rel;
  }
  return hit;
}

const products = {};
for (const [code, prefix] of PRODUCTS) {
  const rel = latestFor(prefix);
  if (!rel) {
    const prev = previous && previous.products && previous.products[code];
    if (prev) {
      products[code] = prev;
      console.log(`${code}: monorepo 尚无 ${prefix}/* release，沿用旧条目 ${prev.version}`);
    } else {
      console.warn(`${code}: monorepo 尚无 ${prefix}/* release，且无旧条目可沿用`);
    }
    continue;
  }
  const assets = rel.assets || [];
  products[code] = {
    repo: MONO_REPO,
    version: rel.tag_name,
    published: rel.published_at,
    windows: entry(pick(assets, WIN_PREFS)),
    macos: {
      aarch64: entry(pick(assets, [/_aarch64\.dmg$/i])),
      x64: entry(pick(assets, [/_x64\.dmg$/i])),
    },
  };
  console.log(`${code}: ${rel.tag_name}`);
}

/* 内容没变就沿用旧的 generated：否则每次定时任务都会因时间戳不同而提交一次空变更。 */
const unchanged =
  previous && JSON.stringify(previous.products) === JSON.stringify(products);

const data = {
  generated: unchanged ? previous.generated : new Date().toISOString(),
  note:
    "SHA-256 digests as published by GitHub for each release asset. " +
    "Verify with: Get-FileHash <file> -Algorithm SHA256  |  shasum -a 256 <file>",
  products,
};

writeFileSync(OUT, JSON.stringify(data, null, 2) + "\n");
console.log(`wrote ${OUT}`);
